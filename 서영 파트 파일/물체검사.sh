#!/usr/bin/env bash
set -euo pipefail


# ==============================================================================
# 기본 경로
# ==============================================================================

BASE="/home/seoyeong/졸업작품/전처리와구조광_통합"

SAMPLE_DIR="$BASE/플랫폼 바닥 따기/구조광_전처리/샘플"

cd "$BASE"


# ==============================================================================
# 보조 함수
# ==============================================================================

step() {

    echo
    echo "========================================================================"
    echo "▶ $1"
    echo "========================================================================"
    echo

}


fail() {

    echo
    echo "========================================================================"
    echo "❌ 오류"
    echo "========================================================================"
    echo "$1"
    echo
    exit 1

}


# ==============================================================================
# 시작 안내
# ==============================================================================

echo
echo "========================================================================"
echo "                  새 물체 구조광 검사 시작"
echo "========================================================================"
echo
echo "검사할 물체를 플랫폼 위에 올려주세요."
echo
echo "기존 초기 세팅값:"
echo "  - 프로젝터 X/Y 범위"
echo "  - 빈 플랫폼 Depth 기준"
echo
echo "을 그대로 사용합니다."
echo "========================================================================"
echo

read -rp "물체 배치가 완료되었으면 Enter를 누르세요..."


# ==============================================================================
# 1. 구조광 촬영 및 전처리
# ==============================================================================

step "1/6 구조광 촬영 및 전처리"

python3 \
    "$BASE/구조광_전처리_최종_v2_현재프레임플랫폼기준_Depth홀위상보강_경로수정_0822.py"


# ==============================================================================
# 최신 촬영 폴더 자동 검색
# ==============================================================================

RUN_DIR="$(
    find "$SAMPLE_DIR" \
        -maxdepth 1 \
        -mindepth 1 \
        -type d \
        -name '촬영_*' \
    | sort \
    | tail -n 1
)"


if [ -z "$RUN_DIR" ]; then

    fail "촬영_* 폴더를 찾지 못했습니다."

fi


echo
echo "✅ 이번 촬영:"
echo "$RUN_DIR"


ROOT="$RUN_DIR/전처리_결과/구조광_형상복원"

V2_DIR="$ROOT/최종자동통합/04_현재프레임플랫폼기준_최종_v2_Depth홀위상보강"


# ==============================================================================
# 2. DC GrabCut 물체 마스크
# ==============================================================================

step "2/6 DC + GrabCut 물체 마스크 생성"

python3 \
    "$BASE/make_dc_grabcut_object_mask_latest.py"


# ==============================================================================
# 필요한 입력 경로
# ==============================================================================

WRAPPED="$V2_DIR/07_relative_wrapped.npy"

MASK="$ROOT/DC_GRABCUT_OBJECT_MASK/dc_grabcut_object_mask.npy"

OUT="$V2_DIR/FINAL_DC_MASK_PHASE_z30_SIGN_PLUS.ply"


echo
echo "------------------------------------------------------------------------"
echo "Phase 입력"
echo "$WRAPPED"
echo
echo "물체 Mask"
echo "$MASK"
echo "------------------------------------------------------------------------"


if [ ! -f "$WRAPPED" ]; then

    fail "07_relative_wrapped.npy를 찾지 못했습니다."

fi


if [ ! -f "$MASK" ]; then

    fail "dc_grabcut_object_mask.npy를 찾지 못했습니다."

fi


# ==============================================================================
# 3. Phase 재언래핑 + 물체 Point Cloud
# ==============================================================================

step "3/6 Phase 재언래핑 + 물체 Point Cloud 생성"

python3 \
    "$BASE/make_phase_relative_reunwrap_holefilled_0822.py" \
    --wrapped "$WRAPPED" \
    --mask "$MASK" \
    --out "$OUT" \
    --z_scale 30 \
    --z_sign 1 \
    --step 2 \
    --smooth_ksize 1 \
    --remove_plane


if [ ! -f "$OUT" ]; then

    fail "물체 Point Cloud 생성에 실패했습니다."

fi


echo
echo "✅ 물체 Point Cloud:"
echo "$OUT"


# ==============================================================================
# 4. 플랫폼 바닥 추가
# ==============================================================================

step "4/6 플랫폼 바닥 Point Cloud 추가"

python3 \
    "$BASE/add_platform_floor_latest.py"


# ==============================================================================
# 최신 WITH_FLOOR 파일 검색
# ==============================================================================

PLY="$(
    find "$V2_DIR" \
        -maxdepth 1 \
        -type f \
        -name '*WITH_FLOOR.ply' \
        -printf '%T@ %p\n' \
    | sort -n \
    | tail -n 1 \
    | cut -d' ' -f2-
)"


if [ -z "$PLY" ] || [ ! -f "$PLY" ]; then

    fail "바닥 포함 WITH_FLOOR PLY를 찾지 못했습니다."

fi


echo
echo "✅ 바닥 포함 Point Cloud:"
echo "$PLY"


# ==============================================================================
# 5. CloudCompare 시각화
# ==============================================================================

step "5/6 CloudCompare에서 바닥 포함 결과 열기"


if command -v CloudCompare >/dev/null 2>&1; then

    CloudCompare "$PLY" >/dev/null 2>&1 &

elif command -v cloudcompare >/dev/null 2>&1; then

    cloudcompare "$PLY" >/dev/null 2>&1 &

else

    echo "⚠️ CloudCompare 실행 명령을 찾지 못했습니다."
    echo
    echo "PLY는 정상 생성되었습니다:"
    echo "$PLY"

fi


# ==============================================================================
# 6. 평면 검출 + 3축 Pose 계산
#
# 중요:
# 바닥이 추가된 WITH_FLOOR가 아니라
# 원래 물체 Point Cloud를 분석함.
# ==============================================================================

step "6/6 평면 검출 + 3축 플랫폼 Pose 계산"

python3 \
    "$BASE/0823_test.py" \
    "$OUT"


# ==============================================================================
# 최종 결과
# ==============================================================================

echo
echo
echo "========================================================================"
echo " 🎉 새 물체 검사 전체 완료"
echo "========================================================================"
echo
echo "이번 촬영:"
echo "$RUN_DIR"
echo
echo "물체 Point Cloud:"
echo "$OUT"
echo
echo "바닥 포함 Point Cloud:"
echo "$PLY"
echo
echo "평면 분할 결과는 0823_test.py에서 자동 저장 및"
echo "CloudCompare로 열립니다."
echo
echo "========================================================================"
